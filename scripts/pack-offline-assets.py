#!/usr/bin/env python3
"""Packs fonts, logos, borders, example photos, and JSON data into js/offline-bundle.js
so index.html works seamlessly when opened directly via file:// (double-click in Finder)
while still loading live data/signatories.json when hosted over HTTP/HTTPS."""

import base64, json, mimetypes, pathlib

root = pathlib.Path(__file__).resolve().parent.parent

font_map = {
    "regular": "assets/fonts/Gelasio-Regular.ttf",
    "bold": "assets/fonts/Gelasio-Bold.ttf",
    "italic": "assets/fonts/Gelasio-Italic.ttf",
    "boldItalic": "assets/fonts/Gelasio-BoldItalic.ttf",
    "displayBold": "assets/fonts/Cinzel-Bold.ttf",
}

asset_paths = [
    "assets/logos/paara-logo.svg",
    "assets/logos/paara-logo-transparent.png",
    "assets/borders/original-cleaned.jpg",
    "assets/examples/doug_teter.jpg",
    "assets/examples/andy_korsak.jpg",
    "assets/examples/ron_chester.jpg",
    "assets/examples/jim_rice.jpg",
    "assets/examples/vic_black.jpg",
    "assets/examples/gerry_tucker.jpg",
]

fonts_b64 = {
    k: base64.b64encode((root / rel).read_bytes()).decode("ascii")
    for k, rel in font_map.items()
}

data_urls = {}
for rel in asset_paths:
    raw = (root / rel).read_bytes()
    mime, _ = mimetypes.guess_type(rel)
    if rel.endswith(".svg"):
        mime = "image/svg+xml"
    b64 = base64.b64encode(raw).decode("ascii")
    data_urls[rel] = f"data:{mime};base64,{b64}"

signatories = json.loads((root / "data/signatories.json").read_text("utf-8"))
examples = json.loads((root / "data/examples.json").read_text("utf-8"))

bundle = {
    "fontsBase64": fonts_b64,
    "dataUrls": data_urls,
    "signatories": signatories,
    "examples": examples,
}

out_file = root / "js/offline-bundle.js"
out_file.write_text(
    "// Auto-generated by scripts/pack-offline-assets.py for file:// offline support.\n"
    "// Embedded fonts (Gelasio, Cinzel) are licensed under SIL Open Font License 1.1:\n"
    "//   Copyright 2022 The Gelasio Project Authors (https://github.com/SorkinType/Gelasio)\n"
    "//   Copyright 2020 The Cinzel Project Authors (https://github.com/NDISCOVER/Cinzel)\n"
    "//   See assets/fonts/OFL.txt for full license text.\n"
    "window.PAARA_OFFLINE = " + json.dumps(bundle, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {out_file} ({out_file.stat().st_size / 1024 / 1024:.2f} MB)")
